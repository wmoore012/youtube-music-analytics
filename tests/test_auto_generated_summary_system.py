    def test_summary_handles_edge_cases_gracefully(self):
        """Test that summary system handles edge cases gracefully."""
        from youtubeviz.summary_generator import generate_markdown_summary

        # Test with empty data
        empty_performance = pd.DataFrame(columns=["artist_name", "views", "date"])
        empty_sentiment = pd.DataFrame(columns=["artist_name", "sentiment"])

        empty_summary = generate_markdown_summary(empty_performance, empty_sentiment)
        assert isinstance(empty_summary, str), "Should return string even with empty data"
        assert len(empty_summary) > 0, "Should return non-empty summary even with no data"
        assert (
            "no performance or sentiment data" in empty_summary.lower() or "insufficient" in empty_summary.lower()
        ), "Should indicate data limitations"

        # Test with single artist
        single_artist_data = pd.DataFrame(
            {
                "artist_name": ["Solo Artist"] * 5,
                "views": [1000, 1100, 1200, 1300, 1400],
                "date": pd.date_range("2024-01-01", periods=5, freq="D"),
                "engagement_rate": [5.0] * 5,
            }
        )

        single_sentiment = pd.DataFrame(
            {"artist_name": ["Solo Artist"] * 10, "sentiment": ["positive"] * 8 + ["negative"] * 2}
        )

        single_summary = generate_markdown_summary(single_artist_data, single_sentiment)
        assert "Solo Artist" in single_summary, "Should handle single artist data"

