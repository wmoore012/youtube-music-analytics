    def test_pattern_detection_with_different_data_scenarios(self):
        """Test pattern detection with various data scenarios."""
        from youtubeviz.summary_generator import detect_performance_patterns

        # Test with all growth scenario
        growth_data = pd.DataFrame(
            {
                "artist_name": ["Artist A", "Artist B"] * 10,
                "date": pd.date_range("2024-01-01", periods=20, freq="D"),
                "views": [1000 + i * 100 for i in range(20)],  # Steady growth
                "engagement_rate": [5.0] * 20,
            }
        )

        growth_patterns = detect_performance_patterns(growth_data)
        assert len(growth_patterns["growth_artists"]) > 0, "Should detect growth in growth scenario"

        # Test with all decline scenario
        decline_data = pd.DataFrame(
            {
                "artist_name": ["Artist C", "Artist D"] * 10,
                "date": pd.date_range("2024-01-01", periods=20, freq="D"),
                "views": [2000 - i * 50 for i in range(20)],  # Steady decline
                "engagement_rate": [3.0] * 20,
            }
        )

        decline_patterns = detect_performance_patterns(decline_data)
        assert len(decline_patterns["declining_artists"]) > 0, "Should detect decline in decline scenario"

